-- One analysis per product and language. Before this, each product row held a single analysis,
-- so every switch between Greek and English replaced it and re-ran the database lookups and the AI.

CREATE TABLE product_analysis (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    lang             varchar(2) NOT NULL,
    health_score     integer,
    score_source     varchar(255),
    explanation      text,
    origin           text,
    nutrition        text,
    ingredients_json text,
    pros_json        text,
    cons_json        text,
    analyzed_at      timestamp(6) with time zone,
    CONSTRAINT product_analysis_product_lang_key UNIQUE (product_id, lang)
);

-- Keep the analyses already made: each product row held one, in one language
INSERT INTO product_analysis (product_id, lang, health_score, score_source, explanation, origin, nutrition,
                              ingredients_json, pros_json, cons_json)
SELECT id, lang, health_score, score_source, explanation, origin, nutrition, ingredients_json, pros_json, cons_json
FROM products
WHERE lang IN ('el', 'en') AND health_score IS NOT NULL;

ALTER TABLE products
    DROP COLUMN lang,
    DROP COLUMN health_score,
    DROP COLUMN score_source,
    DROP COLUMN explanation,
    DROP COLUMN origin,
    DROP COLUMN nutrition,
    DROP COLUMN ingredients_json,
    DROP COLUMN pros_json,
    DROP COLUMN cons_json;

-- Long names, image links and ingredient lists no longer fail to save on a length limit
ALTER TABLE products
    ALTER COLUMN name TYPE text,
    ALTER COLUMN image_url TYPE text,
    ALTER COLUMN ingredients_text TYPE text;
