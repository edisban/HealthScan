-- The schema as of the move from Hibernate's ddl-auto=update to Flyway.
--
-- Written to be safe on any starting point: an empty database gets both tables, and a
-- database that Hibernate created earlier (possibly before some columns existed) only gets
-- what is missing. Existing rows are never touched. Existing databases are baselined at
-- version 0 (spring.flyway.baseline-version), so this script runs on them too.

CREATE TABLE IF NOT EXISTS products (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode varchar(255) NOT NULL,
    CONSTRAINT products_barcode_key UNIQUE (barcode)
);

ALTER TABLE products ADD COLUMN IF NOT EXISTS name             varchar(255);
ALTER TABLE products ADD COLUMN IF NOT EXISTS image_url        varchar(255);
ALTER TABLE products ADD COLUMN IF NOT EXISTS ingredients_text varchar(4000);
ALTER TABLE products ADD COLUMN IF NOT EXISTS health_score     integer;
ALTER TABLE products ADD COLUMN IF NOT EXISTS explanation      varchar(2000);
ALTER TABLE products ADD COLUMN IF NOT EXISTS lang             varchar(255);
ALTER TABLE products ADD COLUMN IF NOT EXISTS source           varchar(255);
ALTER TABLE products ADD COLUMN IF NOT EXISTS origin           varchar(255);
ALTER TABLE products ADD COLUMN IF NOT EXISTS nutrition        varchar(2000);
ALTER TABLE products ADD COLUMN IF NOT EXISTS ingredients_json text;
ALTER TABLE products ADD COLUMN IF NOT EXISTS pros_json        text;
ALTER TABLE products ADD COLUMN IF NOT EXISTS cons_json        text;
ALTER TABLE products ADD COLUMN IF NOT EXISTS nutri_score      varchar(255);
ALTER TABLE products ADD COLUMN IF NOT EXISTS nova_group       integer;
ALTER TABLE products ADD COLUMN IF NOT EXISTS additives_count  integer;
ALTER TABLE products ADD COLUMN IF NOT EXISTS score_source     varchar(255);

-- Barcodes the web search could not identify, remembered for a day
CREATE TABLE IF NOT EXISTS web_search_misses (
    barcode     varchar(255) PRIMARY KEY,
    searched_at timestamp(6) with time zone
);
